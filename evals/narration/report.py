"""Repeat runs of the narration pipeline on the demo's big moments.

The same prompt gives different lines each run, so one run proves nothing:
each moment runs N times per persona, and we report first-pass, retry and
fallback rates with Wilson intervals, the top rejection reasons and the cost.
Translations get a smaller spot check (each language kept or dropped).

Results belong to the model that produced them: a Gemini rate says nothing
about gpt-4.1-mini. The full report runs on the Foundry models (Phase 6).

    MAX_RUN_USD=0.50 uv run python -m evals.narration.report --runs 10 \\
        --translation-runs 2
Writes the "narration" section of docs/EVAL.md.
"""

import argparse
import asyncio
import re
import time
from collections import Counter
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from agents.llm import LLMClient, from_env
from agents.mcp_server.data import MatchData
from agents.pipeline import prompts
from agents.pipeline.facts import task_for
from agents.pipeline.workflow import narrate
from evals.moments.report import wilson
from evals.sections import write_section

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "EVAL.md"
MIN_IMPORTANCE = 0.9
PERSONAS = ["casual", "analyst"]

# Verifier reasons -> short labels (first match wins).
REASONS = [
    ("is not in the values", "number not in the evidence"),
    ("no code-made count", "count word not in the evidence"),
    ("nothing in the evidence happened", "count word not in the evidence"),
    ("does not match any before/after", "comparison word wrong"),
    ("casual line", "decimals in a casual line"),
    ("is not a team or a player", "unknown name"),
    ("wrong about the score", "wrong team leading"),
    ("numbers are", "numbers given to the wrong team"),
    ("say it came from a counter", "counter not named"),
    ("name the zone", "zone not named"),
    ("too close to a style example", "copied a style example"),
    ("no predictions", "prediction"),
    ("weather", "blamed the weather"),
]


def label(reason: str) -> str:
    return next((short for key, short in REASONS if key in reason), reason[:40])


@dataclass
class Tally:
    runs: int = 0
    first: int = 0
    retried: int = 0
    fallback: int = 0
    errors: int = 0
    reasons: Counter = field(default_factory=Counter)


async def run(
    data: MatchData, llm: LLMClient, runs: int, translation_runs: int
) -> tuple[dict[str, Tally], dict[str, list[int]]]:
    moments = [m for m in data.moments if m.importance >= MIN_IMPORTANCE]
    tallies = {p: Tally() for p in PERSONAS}
    kept = {lang: [0, 0] for lang in prompts.LANGUAGE}  # [kept, tried]
    for r in range(runs):
        for moment in moments:
            for persona in PERSONAS:
                languages = list(prompts.LANGUAGE) if r < translation_runs else []
                t = tallies[persona]
                t.runs += 1
                try:
                    out = await narrate(llm, task_for(data, moment, persona, languages))
                # Any model, network or provider failure is counted, not hidden;
                # BudgetExceeded too (the kill switch must show in the report).
                except Exception as e:  # noqa: BLE001
                    t.errors += 1
                    t.reasons[f"error: {type(e).__name__}"] += 1
                    continue
                if out.fallback:
                    t.fallback += 1
                elif out.attempts == 1:
                    t.first += 1
                else:
                    t.retried += 1
                for v in out.verdicts:
                    t.reasons.update({label(x) for x in v.reasons})
                for lang in languages:
                    kept[lang][1] += 1
                    kept[lang][0] += lang in out.overlay.text
    return tallies, kept


def rate(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({k / n:.0%}; 95% CI {lo:.0%}-{hi:.0%})" if n else "-"


def render(
    tallies: dict[str, Tally],
    kept: dict[str, list[int]],
    llm: LLMClient,
    runs: int,
    translation_runs: int,
    seconds: float,
) -> str:
    b = llm.budget
    kes = sum(row.get("kes") or 0 for row in b.ledger)
    lines = [
        "## Narration: repeat runs",
        "",
        (
            f"Generated by `uv run python -m evals.narration.report` on "
            f"{datetime.now(UTC):%Y-%m-%d}. Model: **{llm.provider.model}** "
            f"(results belong to this model only). Demo moments with importance "
            f">= {MIN_IMPORTANCE}, {runs} runs per persona (English); translations "
            f"spot-checked on {translation_runs} of those runs."
        ),
        "",
        (
            "First pass = the first line passed the Verifier; retried = passed "
            "after 1-2 retries; fallback = 3 rejections, the code template aired."
        ),
        "",
        "| Persona | Lines | First pass | Retried | Fallback | Errors |",
        "|---|---|---|---|---|---|",
    ]
    for persona, t in tallies.items():
        lines.append(
            f"| {persona} | {t.runs} | {rate(t.first, t.runs)} | "
            f"{rate(t.retried, t.runs)} | {rate(t.fallback, t.runs)} | {t.errors} |"
        )
    lines += ["", "Top rejection reasons (drafts rejected for each):", ""]
    total = sum((t.reasons for t in tallies.values()), Counter())
    lines += [f"- {reason}: {n}" for reason, n in total.most_common(8)] or ["- none"]
    lines += ["", "| Language | Translations kept |", "|---|---|"]
    for lang, (k, n) in kept.items():
        rtl = " (right-to-left)" if lang in prompts.RIGHT_TO_LEFT else ""
        lines.append(f"| {prompts.LANGUAGE[lang]}{rtl} | {rate(k, n)} |")
    n_lines = sum(t.runs for t in tallies.values())
    lines += [
        "",
        (
            f"Cost: {len(b.ledger)} model calls, {b.tokens_spent} tokens, "
            f"${b.usd_spent:.4f} (KES {kes:.2f}); "
            f"${b.usd_spent / max(n_lines, 1):.5f} per line. Wall time "
            f"{seconds / 60:.1f} min (paced to the free-tier request limit)."
        ),
    ]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--match-file", type=Path, default=Path("demo/match.jsonl"))
    p.add_argument("--runs", type=int, default=10)
    p.add_argument("--translation-runs", type=int, default=2)
    args = p.parse_args()
    llm = from_env()
    data = MatchData.from_file(args.match_file)
    start = time.monotonic()
    tallies, kept = asyncio.run(run(data, llm, args.runs, args.translation_runs))
    body = render(
        tallies, kept, llm, args.runs, args.translation_runs, time.monotonic() - start
    )
    write_section(OUT, "narration", body)
    print(re.sub(r"\n{2,}", "\n", body))


if __name__ == "__main__":
    main()
