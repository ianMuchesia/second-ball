"""Latency per stage, live, on the demo: replayer -> Kafka -> live narrator.

    make up   # Kafka (or KAFKA_BOOTSTRAP_SERVERS pointing at one)
    uv run python -m evals.latency.report --speed 10     # fake model; --provider gemini asks first

Stages come from the traces (agents.telemetry spans) and the live service's
clocks: Kafka transport, the detector per event, the wait in the job queue,
each agent and MCP call, the Verifier, the Localizer, and the delay a viewer
sees from a moment firing to its line on air. Writes the "latency" section
of docs/EVAL.md. With the fake model it measures our code; with a real model
on the free tier, request pacing dominates.
"""

import argparse
import asyncio
import math
import uuid
from datetime import UTC, datetime
from pathlib import Path

from agents.live import Live
from agents.live.__main__ import kafka_sink, serve
from agents.llm import from_env
from agents.llm.guard import add_flags, confirm, match_requests
from agents.telemetry import RECORDER, setup
from evals.sections import write_section
from stream import kafka
from stream.replayer import replay, wait_for_group

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "EVAL.md"
STAGES = [
    ("narrate", "whole pipeline, one moment and persona"),
    ("analyst", "Analyst step (MCP + model)"),
    ("mcp.get_sequence", "MCP tool call"),
    ("llm.analyst", "Analyst model call"),
    ("narrator", "Narrator step (per attempt)"),
    ("llm.narrator", "Narrator model call"),
    ("verifier", "Verifier (code)"),
    ("llm.localizer", "Localizer model call (per language)"),
    ("recap", "recap (per persona)"),
    ("producer.offer", "Producer decision"),
]


def pct(xs: list[float], q: float) -> float:
    xs = sorted(xs)
    return xs[min(len(xs) - 1, round(q * (len(xs) - 1)))] if xs else float("nan")


def ms(x: float) -> str:
    return "-" if math.isnan(x) else f"{x * 1000:.1f}"


async def run(path: Path, speed: float, languages: list[str], llm):
    setup()
    RECORDER.clear()
    kafka.ensure_topic(kafka.TOPIC)
    from confluent_kafka import Consumer

    group = f"latency-{uuid.uuid4().hex[:8]}"
    consumer = Consumer(
        kafka.config(
            **{
                "group.id": group,
                "enable.auto.commit": False,
                "auto.offset.reset": "latest",
            }
        )
    )
    consumer.subscribe([kafka.TOPIC])
    sink = kafka_sink("overlays")
    out = []
    live = Live(
        llm,
        lambda o: (sink(o), out.append(o)),
        languages=languages,
        speed=speed,
    )
    served = asyncio.create_task(serve(live, consumer, exit_on_end=True))
    await asyncio.to_thread(wait_for_group, group)
    await asyncio.to_thread(replay, path, speed)
    await served
    consumer.close()
    sink.flush(10)
    return live, llm, out


def render(live: Live, llm, out, speed: float, languages) -> str:
    spans: dict[str, list[float]] = {}
    for s in RECORDER.spans:
        spans.setdefault(s.name, []).append((s.end_time - s.start_time) / 1e9)
    st = live.stats
    rows = [
        ("Kafka transport (replayer -> live)", st.transport_s),
        ("Moment detector (per event)", st.detect_s),
        ("Job queue wait", st.queue_s),
        *((f"{label} (`{name}`)", spans.get(name, [])) for name, label in STAGES),
    ]
    lines = [
        "## Latency per stage (live, demo)",
        "",
        (
            f"Generated by `uv run python -m evals.latency.report` on "
            f"{datetime.now(UTC):%Y-%m-%d}: the demo replayed into Kafka at "
            f"{speed:g}x and narrated live. Model: **{llm.provider.model}**; "
            f"languages: {', '.join(languages) or 'English only'}."
        ),
        "",
        "| Stage | n | p50 (ms) | p95 (ms) |",
        "|---|---|---|---|",
    ]
    for label, xs in rows:
        lines.append(
            f"| {label} | {len(xs)} | {ms(pct(xs, 0.5))} | {ms(pct(xs, 0.95))} |"
        )
    d = st.air_delay_s
    lines.append(
        f"| Moment fired -> line on air (viewer seconds) | {len(d)} | "
        f"{pct(d, 0.5):.1f} s | {pct(d, 0.95):.1f} s |"
    )
    o = st.outcomes
    narr = [x for x in out if x.slot == "narrative"]
    lines += [
        "",
        (
            f"Narrative lines: {o['aired']} aired, {o['expired']} expired in the "
            f"queue (the one-per-45-s rule), {o['skipped_stale']} skipped before "
            f"any model call (already stale); {len(narr)} narrative updates and "
            f"{sum(x.slot == 'recap' for x in out)} recaps published. Cost "
            f"${llm.budget.usd_spent:.4f}."
        ),
    ]
    return "\n".join(lines)


def main():
    from dotenv import load_dotenv

    load_dotenv()
    p = argparse.ArgumentParser()
    p.add_argument("--match-file", type=Path, default=Path("demo/match.jsonl"))
    p.add_argument("--speed", type=float, default=10)
    p.add_argument("--languages", default="fr,es,sw,ar")
    add_flags(p)
    args = p.parse_args()
    languages = [x for x in args.languages.split(",") if x]
    llm = from_env(provider=args.provider)
    if args.provider != "fake":
        n = match_requests(args.match_file, languages)
        confirm(llm, f"About {n} requests (a free dry run of this match)", args.yes)
    live, llm, out = asyncio.run(run(args.match_file, args.speed, languages, llm))
    body = render(live, llm, out, args.speed, languages)
    write_section(OUT, "latency", body)
    print(body)


if __name__ == "__main__":
    main()
