"""Moment detector eval -> docs/EVAL.md.

    uv run python -m evals.moments.report        (make eval-moments)

1. The demo scenario against its answer key (expected_moments): recall and
   precision with Wilson 95% intervals. Kinds are matched with Ian's mapping
   (DECISIONS.md, 2026-10-22); a detection matches an expected moment when
   the kind maps, the team agrees (match-wide expects any team) and its
   minute is inside the expected range +- TOLERANCE_MIN.
2. 50 free_simulation matches: moments per match, by kind (a spam check).
   The thresholds are not tuned to the demo alone.
"""

import math
import multiprocessing
import statistics
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from datetime import UTC, datetime
from pathlib import Path

from core.metrics import Events
from core.moments import KINDS, detect
from engine.core import simulate_match
from engine.league import load_league
from engine.scenarios import expected_moments, load_scenario
from evals.realism.report import fixtures
from evals.sections import keep_sections

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "EVAL.md"
DEMO = "demo_riverside_harbour"
FREE_MATCHES, FREE_FIRST_SEED = 50, 60_000
TOLERANCE_MIN = 1

# Ian, 2026-10-22: answer-key kinds -> detector kinds.
MAPPING = {
    "control_rising": {"control_shift"},
    "control_drop": {"control_shift"},
    "field_tilt": {"control_shift"},
    "chaos_rising": {"openness_spike"},
    "open_spell": {"openness_spike"},
    "chance": {"big_chance"},
    "block_drop": {"shape_change"},
    "counter_behind_fullback": {"big_chance", "repeated_pattern"},
    "counter_threat_rising": {"big_chance", "repeated_pattern"},
}


def detector_kinds(kind: str) -> set[str]:
    return MAPPING.get(kind, {kind})


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def matches(expected: dict, moment) -> bool:
    lo, hi = expected["minute"]
    minute = moment.clock.minute
    return (
        moment.kind in detector_kinds(expected["kind"])
        and (expected["team"] is None or moment.team == expected["team"])
        and lo - TOLERANCE_MIN <= minute <= hi + TOLERANCE_MIN
    )


def run_demo():
    sc = load_scenario(DEMO)
    league = load_league()
    m = simulate_match(
        league[sc.home],
        league[sc.away],
        sc.seed,
        weather=sc.weather,
        kickoff=sc.kickoff,
        scenario=sc,
    )
    key = expected_moments(sc, m.match)["moments"]
    moments = detect(Events.for_match(m.match, m.events))
    found = [any(matches(x, mo) for mo in moments) for x in key]
    covered = {k for x in key for k in detector_kinds(x["kind"])}
    in_scope = [mo for mo in moments if mo.kind in covered]
    hits = [mo for mo in in_scope if any(matches(x, mo) for x in key)]
    return key, moments, found, in_scope, hits


def free(fixture):
    home, away, seed = fixture
    league = load_league()
    m = simulate_match(league[home], league[away], seed)
    return Counter(mo.kind for mo in detect(Events.for_match(m.match, m.events)))


def run_free():
    with ProcessPoolExecutor(mp_context=multiprocessing.get_context("spawn")) as pool:
        return list(
            pool.map(free, fixtures(FREE_MATCHES, FREE_FIRST_SEED), chunksize=4)
        )


def pct(lo_hi) -> str:
    return f"{lo_hi[0]:.0%} - {lo_hi[1]:.0%}"


def render(demo, per_match) -> str:
    key, moments, found, in_scope, hits = demo
    recall_k, recall_n = sum(found), len(found)
    prec_k, prec_n = len(hits), len(in_scope)
    rows = "\n".join(
        f"| {x['kind']} | {x['team'] or 'match'} | {x['minute'][0]}-{x['minute'][1]} | "
        f"{', '.join(sorted(detector_kinds(x['kind'])))} | {'found' if ok else '**missed**'} |"
        for x, ok in zip(key, found, strict=True)
    )
    totals = [sum(c.values()) for c in per_match]
    by_kind = "\n".join(
        f"| {k} | {statistics.mean(c[k] for c in per_match):.1f} | "
        f"{max(c[k] for c in per_match)} |"
        for k in KINDS
    )
    demo_kinds = Counter(mo.kind for mo in moments)
    today = datetime.now(UTC).date().isoformat()
    return f"""# Moment detector eval

Generated by `uv run python -m evals.moments.report` on {today}. Thresholds:
`core/moments/config.yaml` (red zone, TUNABLE, owner: Ian). Not tuned to the
demo alone: the spam check below runs on {FREE_MATCHES} free matches.

## Demo scenario vs its answer key

The demo is **scripted** (Riverside v Harbour, `{DEMO}`). Answer-key kinds are
matched to detector kinds with Ian's mapping (DECISIONS.md, 2026-10-22); the
minute may be off by {TOLERANCE_MIN}.

- **Recall:** {recall_k} of {recall_n} expected moments found =
  **{recall_k / recall_n:.0%}** (Wilson 95%: {pct(wilson(recall_k, recall_n))}).
- **Precision** (detections of kinds the answer key covers): {prec_k} of
  {prec_n} match an expected moment = **{prec_k / max(prec_n, 1):.0%}**
  (Wilson 95%: {pct(wilson(prec_k, prec_n))}). The answer key lists the story's
  big moments only, so a detection outside it is not necessarily wrong.
- Detected in the demo: {len(moments)} moments
  ({", ".join(f"{k} {n}" for k, n in demo_kinds.most_common())}).

| Expected kind | Team | Minutes | Detector kind(s) | Result |
|---|---|---|---|---|
{rows}

## Spam check: {FREE_MATCHES} free matches

Moments per match: mean **{statistics.mean(totals):.1f}**, min {min(totals)},
max {max(totals)} (about {statistics.mean(totals) / 95:.2f} per minute).

| Kind | Mean per match | Max in a match |
|---|---|---|
{by_kind}

## Known limits

- Red-card impact compares the 10 minutes before and after the card, so it is
  detected 10 minutes later; its clock is the red card's.
- Control shift compares consecutive 10-minute windows from 20' on, so a team
  taking control in the first minutes is not a "shift".
- Counters (for repeated_pattern) are read from events only: ball won in
  the team's own half, then within 10 s a 20 m+ forward pass into a wide
  channel beyond the defenders' back line. Full-back roles are not in the
  feed, so "behind the same full-back" = the same side of the same defence.
"""


def main():
    demo = run_demo()
    per_match = run_free()
    OUT.write_text(
        keep_sections(render(demo, per_match), OUT, ["narration", "latency"])
    )
    _, _, found, in_scope, hits = demo
    print(
        f"demo recall {sum(found)}/{len(found)}, precision {len(hits)}/{len(in_scope)}; "
        f"free matches: {statistics.mean(sum(c.values()) for c in per_match):.1f} moments/match"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
